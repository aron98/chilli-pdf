//! Regenerate `assets/manifest.txt` — the SHA-256 manifest embedded into
//! the binary by `src/assets.rs`.
//!
//! Run after **any** change under `assets/v1/` (including dropping in the
//! real PDFium/Tesseract binaries and traineddata files):
//!
//! ```text
//! cargo run --example update_asset_manifest
//! ```
//!
//! Swapping bundled assets is data-only: replace the files, rerun this
//! example, and bump `ASSET_VERSION` in `src/assets.rs`. The in-crate test
//! `embedded_bundle_matches_manifest` fails when the manifest is stale.

use std::fs;
use std::path::{Path, PathBuf};

use sha2::{Digest, Sha256};

const HEADER: [&str; 3] = [
    "# chilli-pdf bundled-asset manifest.",
    "# Generated by: cargo run --example update_asset_manifest  (do not edit by hand)",
    "# Format: <sha256-hex> <size-bytes> <relative-path>",
];

fn main() {
    let crate_root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let bundle = crate_root.join("assets").join("v1");
    let manifest_path = crate_root.join("assets").join("manifest.txt");

    let mut names: Vec<String> = Vec::new();
    collect_files(&bundle, &bundle, &mut names).expect("walk assets/v1");
    names.sort();
    if names.is_empty() {
        panic!("no assets found under {}", bundle.display());
    }

    let mut text = String::new();
    for line in HEADER {
        text.push_str(line);
        text.push('\n');
    }
    for name in &names {
        let bytes = fs::read(bundle.join(name)).expect("read bundled asset");
        let digest = hex::encode(Sha256::digest(&bytes));
        text.push_str(&format!("{digest} {} {name}\n", bytes.len()));
    }

    if fs::read_to_string(&manifest_path).unwrap_or_default() == text {
        println!("assets/manifest.txt is up to date ({} files)", names.len());
        return;
    }
    fs::write(&manifest_path, &text).expect("write assets/manifest.txt");
    println!("rewrote assets/manifest.txt for {} files", names.len());
}

/// Recursively collect file paths relative to `root`.
fn collect_files(dir: &Path, root: &Path, out: &mut Vec<String>) -> std::io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        if path.is_dir() {
            collect_files(&path, root, out)?;
        } else {
            let relative = path
                .strip_prefix(root)
                .expect("path inside the bundle")
                .to_string_lossy()
                .replace('\\', "/");
            out.push(relative);
        }
    }
    Ok(())
}
